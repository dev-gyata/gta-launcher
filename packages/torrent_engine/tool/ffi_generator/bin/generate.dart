    'te_cached_bytes',
    'te_request_piece',
    'te_copy_piece',
    'te_release_piece',
    'te_close',
    'te_disk_usage',
  };
  FfiGenerator(
    input: Input(entryPoints: [root.resolve('native/torrent_engine.h')]),
    visitors: [
      Visitor(
        func: (node) {
          node.isIncluded = functions.contains(node.originalName);
          node.recordUse = true;
        },
      ),
    ],
    output: Output(
      dart: DartOutput(
        path: root.resolve('lib/src/third_party/torrent_engine.g.dart'),
